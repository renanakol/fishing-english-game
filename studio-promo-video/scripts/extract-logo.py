"""Extracts the logo's vector shapes from the Illustrator sticker (scripts/logo-source.pdf) into
src/logoParts.ts, so the end card can build the logo piece by piece.

The sticker also holds a "תודה רבה!" headline (glyphs) and a circle border; only the filled logo shapes are kept.
Usage: pdftocairo -svg scripts/logo-source.pdf /tmp/logo.svg && python3 scripts/extract-logo.py /tmp/logo.svg
"""
import json
import re
import sys

svg = open(sys.argv[1], encoding="utf-8").read()
# Skip the glyph definitions; only top-level filled paths make up the logo.
body = svg[svg.index("</defs>"):]
parts = []
for m in re.finditer(r"<path ([^>]*?)/>", body):
    attrs = m.group(1)
    fill = re.search(r'fill="rgb\(([\d.]+)%, ([\d.]+)%, ([\d.]+)%\)"', attrs)
    d = re.search(r' d="([^"]+)"', " " + attrs)
    if not fill or not d or "transform" in attrs:
        continue
    r, g, b = (round(float(v) * 2.55) for v in fill.groups())
    nums = [float(v) for v in re.findall(r"-?\d+\.?\d*", d.group(1))]
    xs, ys = nums[0::2], nums[1::2]
    box = [min(xs), min(ys), max(xs), max(ys)]
    red = r > 150
    if red and box[1] >= 104:
        kind = "text"
    elif red:
        kind = "thread"
    elif box[0] > 94 and box[1] > 76:
        kind = "dots"
    else:
        kind = "line"
    rule = re.search(r'fill-rule="([^"]+)"', attrs)
    parts.append({
        "d": d.group(1),
        "color": "#%02X%02X%02X" % (r, g, b),
        "rule": rule.group(1) if rule else "nonzero",
        "kind": kind,
        "box": [round(v, 2) for v in box],
    })

x0 = min(p["box"][0] for p in parts) - 2
y0 = min(p["box"][1] for p in parts) - 2
x1 = max(p["box"][2] for p in parts) + 2
y1 = max(p["box"][3] for p in parts) + 2
with open("src/logoParts.ts", "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/extract-logo.py from scripts/logo-source.pdf. Do not edit by hand.\n")
    f.write(f"export const logoViewBox = {json.dumps([round(x0, 2), round(y0, 2), round(x1 - x0, 2), round(y1 - y0, 2)])};\n")
    f.write("export type LogoPart = { d: string; color: string; rule: string; kind: string; box: number[] };\n")
    f.write(f"export const logoParts: LogoPart[] = {json.dumps(parts, ensure_ascii=False, indent=1)};\n")
print({k: sum(1 for p in parts if p["kind"] == k) for k in ("line", "dots", "thread", "text")})
