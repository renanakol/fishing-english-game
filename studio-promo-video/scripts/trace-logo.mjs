// Vectorizes public/logo/logo.png into src/logoPaths.ts so the logo can be drawn on stroke by stroke.
// The logo has two inks (navy figure/letters, red text); each is traced separately.
// Usage: node scripts/trace-logo.mjs
import potrace from "potrace";
import { writeFileSync } from "node:fs";
import { promisify } from "node:util";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
// potrace bundles jimp 0.14, whose default export is the Jimp class.
const Jimp = require("jimp");
const trace = promisify(potrace.trace);
const src = new URL("../public/logo/logo.png", import.meta.url).pathname;

const inks = {
  navy: ([r, g, b]) => b > r + 20 && r < 90,
  red: ([r, g, b]) => r > 150 && g < 120 && b < 120,
};

const image = await Jimp.read(src);
const { width, height } = image.bitmap;
const out = {};
for (const [name, test] of Object.entries(inks)) {
  // Paint the matching ink black on white; potrace traces the black.
  const mask = image.clone();
  mask.scan(0, 0, width, height, function (x, y, idx) {
    const d = this.bitmap.data;
    const on = d[idx + 3] > 128 && test([d[idx], d[idx + 1], d[idx + 2]]);
    d[idx] = d[idx + 1] = d[idx + 2] = on ? 0 : 255;
    d[idx + 3] = 255;
  });
  const svg = await trace(mask, { turdSize: 8, optTolerance: 0.3 });
  out[name] = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
}

writeFileSync(
  new URL("../src/logoPaths.ts", import.meta.url),
  `// Generated by scripts/trace-logo.mjs from public/logo/logo.png. Do not edit by hand.\n` +
    `export const logoSize = { width: ${width}, height: ${height} };\n` +
    `export const logoPaths = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.reduce((n, d) => n + d.length, 0)])));
